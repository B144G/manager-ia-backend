'use strict';
// Vague 3 · Décisions à seuils, projets (budget, temps, charge, jalons, dépendances, récurrence, pièces), juridique (registres, conformité),
// procédures (versions, accusé de lecture, révision), équipe (journal d'audit, transfert de propriété).
// Lancez-le avec : node scripts/test-wave3-ops.js
const { run } = require('./lib/wave1');
const iso = (d) => d.toISOString().slice(0, 10);
const addDays = (n) => iso(new Date(Date.now() + n * 86400000));
const PNG = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.from('PIECE-PROJET-0123456789')]);

run('Vague 3 · Décisions, projets, juridique, procédures, équipe', async ({ check, owner, mgr, mem, other, org, ws, O, dbx }) => {
  const D = `${O}/decisions`;
  const members = (await owner('GET', `${O}/members`)).json.members;
  const memId = members.find((m) => m.name === 'Paul').userId; const mgrId = members.find((m) => m.name === 'Marc').userId;

  // ---------- Décisions ----------
  let r = await mgr('PUT', `${D}/rules`, { rules: [{ minAmount: 0, role: 'manager' }] });
  check('seuils : réservés aux administrateurs', r.status === 403);
  r = await owner('PUT', `${D}/rules`, { rules: [{ minAmount: 0, role: 'manager' }, { minAmount: 500000, role: 'admin' }, { minAmount: 2000000, role: 'owner' }] });
  check('seuils enregistrés (3 niveaux)', r.status === 200 && r.json.rules === 3, r.json);
  r = await owner('PUT', `${D}/rules`, { rules: [{ minAmount: 10, role: 'chef' }] });
  check('niveau inconnu refusé', r.status === 400);
  r = await mem('POST', D, { title: 'Achat petit matériel', amount: 100000 });
  const d1 = r.json.id;
  check('petit montant : un seul niveau (responsable)', r.status === 201 && JSON.stringify(r.json.levels) === '["manager"]', r.json);
  r = await mem('PUT', `${D}/${d1}`, { status: 'approved' });
  check('un simple membre ne valide pas', r.status === 403);
  r = await mgr('PUT', `${D}/${d1}`, { status: 'approved', note: 'OK' });
  check('le responsable valide', r.status === 200 && r.json.status === 'approved', r.json);
  r = await mem('GET', `${O}/notices`);
  check('le demandeur est notifié de la validation', r.json.items.some((n) => /validée/.test(n.text)), r.json.items);
  r = await mem('POST', D, { title: 'Camion de livraison', amount: 600000 });
  const d2 = r.json.id;
  check('600 000 : circuit à deux niveaux', JSON.stringify(r.json.levels) === '["manager","admin"]', r.json);
  r = await mgr('PUT', `${D}/${d2}`, { status: 'approved' });
  check('niveau 1 validé : la demande reste en attente', r.status === 200 && r.json.status === 'pending', r.json);
  r = await mgr('PUT', `${D}/${d2}`, { status: 'approved' });
  check('le niveau administrateur dépasse le rôle du responsable', r.status === 403, r.json);
  r = await owner('GET', `${D}?status=all`);
  const cur = r.json.decisions.find((d) => d.id === d2);
  check('étapes visibles (1 validée, 1 en attente) et niveau courant', cur.steps[0].status === 'approved' && cur.steps[1].status === 'pending' && cur.currentRole === 'admin', cur);
  r = await owner('PUT', `${D}/${d2}`, { status: 'approved' });
  check('le dernier niveau valide : décision approuvée', r.json.status === 'approved', r.json);
  r = await mem('POST', D, { title: 'Immeuble', amount: 3000000 });
  const d3 = r.json.id;
  check('3 000 000 : trois niveaux', r.json.levels.length === 3, r.json);
  await mgr('PUT', `${D}/${d3}`, { status: 'approved' });
  r = await owner('PUT', `${D}/${d3}`, { status: 'rejected', note: 'Trop cher' });
  check('refus à un niveau intermédiaire : décision refusée', r.json.status === 'rejected', r.json);
  r = await mem('GET', `${O}/notices`);
  check('le demandeur est notifié du refus avec le motif', r.json.items.some((n) => /refusée.*Trop cher/.test(n.text)), r.json.items);
  r = await mgr('POST', D, { title: 'Ma propre demande', amount: 1000 });
  const d4 = r.json.id;
  r = await mgr('PUT', `${D}/${d4}`, { status: 'approved' });
  check('on ne valide pas sa propre demande', r.status === 403);
  r = await owner('PUT', `${D}/${d4}`, { status: 'approved' });
  check('un administrateur peut valider', r.status === 200);
  // délégation
  r = await owner('POST', D, { title: 'Fournitures', amount: 20000 });
  const d5 = r.json.id;
  r = await mem('PUT', `${D}/${d5}`, { status: 'approved' });
  check('sans délégation : refusé', r.status === 403);
  r = await mgr('POST', `${D}/delegations`, { toUserId: memId, until: addDays(5) });
  check('délégation créée', r.status === 201, r.json);
  r = await mgr('POST', `${D}/delegations`, { toUserId: memId, until: addDays(200) });
  check('délégation trop longue refusée (90 jours)', r.status === 400);
  r = await mem('PUT', `${D}/${d5}`, { status: 'approved' });
  check('avec délégation du responsable : validation possible', r.status === 200, r.json);
  r = await mem('POST', D, { title: 'Gros achat', amount: 700000 });
  const d6 = r.json.id;
  await mem('PUT', `${D}/${d6}`, { status: 'approved' });
  r = await mgr('PUT', `${D}/${d6}`, { status: 'approved' });
  r = await mem('PUT', `${D}/${d6}`, { status: 'approved' });
  check('la délégation d\'un responsable ne couvre pas le niveau administrateur', r.status === 403 || r.status === 409, r.status);
  // rappel + lien
  r = await mgr('POST', `${D}/${d6}/remind`, {});
  check('rappel envoyé aux validateurs du niveau courant', r.status === 200);
  r = await owner('GET', `${O}/notices`);
  check('notification de rappel reçue', r.json.items.some((n) => /Rappel/.test(n.text)), r.json.items.map((n) => n.text));
  r = await mgr('POST', `${O}/projects`, { name: 'Projet lié' });
  const linkProj = r.json.id;
  r = await mem('POST', D, { title: 'Budget du projet', amount: 5000, linkKind: 'project', linkId: linkProj });
  check('décision liée à un projet', r.status === 201, r.json);
  r = await mem('GET', `${D}?status=all`);
  check('le lien est visible', r.json.decisions.find((d) => d.id === r.json.decisions[0].id).link.kind === 'project', r.json.decisions[0]);
  r = await mem('POST', D, { title: 'Lien cassé', linkKind: 'project', linkId: 999999 });
  check('lien vers un projet inconnu refusé', r.status === 404);

  // ---------- Projets ----------
  const P = `${O}/projects`;
  r = await mgr('POST', P, { name: 'Ouverture boutique', due: addDays(60) });
  const proj = r.json.id;
  r = await mgr('POST', `${P}/tasks`, { projectId: proj, title: 'Peindre', assigneeId: memId });
  const tA = r.json.id;
  r = await mgr('POST', `${P}/tasks`, { projectId: proj, title: 'Installer les rayons', assigneeId: memId });
  const tB = r.json.id;
  r = await mgr('PUT', `${P}/tasks/${tB}/plan`, { dependsOn: tA, estimateHours: 6 });
  check('dépendance et estimation enregistrées', r.status === 200, r.json);
  r = await mgr('PUT', `${P}/tasks/${tA}/plan`, { dependsOn: tB });
  check('dépendance circulaire refusée', r.status === 400);
  r = await mem('PUT', `${P}/tasks/${tB}`, { status: 'doing' });
  check('une tâche ne démarre pas avant celle dont elle dépend', r.status === 409, r.json);
  r = await mem('PUT', `${P}/tasks/${tA}`, { status: 'done' });
  r = await mem('PUT', `${P}/tasks/${tB}`, { status: 'doing' });
  check('la dépendance terminée, la suite démarre', r.status === 200);
  r = await mgr('PUT', `${P}/${proj}/budget`, { budget: 100000 });
  check('budget du projet fixé', r.status === 200);
  r = await mgr('POST', `${P}/${proj}/costs`, { label: 'Peinture', amount: 30000 });
  check('dépense du projet enregistrée', r.status === 201);
  r = await owner('PUT', `${P}/settings`, { project_hourly_cost: 2000 });
  r = await mem('POST', `${P}/tasks/${tB}/time`, { hours: 5, note: 'Pose' });
  check('temps passé saisi par le membre', r.status === 201, r.json);
  r = await mem('POST', `${P}/tasks/${tB}/time`, { hours: 30 });
  check('plus de 24 h refusé', r.status === 400);
  r = await mgr('GET', `${P}/${proj}/summary`);
  check('coût = dépenses + heures x coût horaire ; reste', r.json.cost.expenses === 30000 && r.json.cost.timeCost === 10000 && r.json.cost.spent === 40000 && r.json.cost.remaining === 60000 && r.json.time.hours === 5, r.json);
  r = await mem('GET', `${P}/${proj}/summary`);
  check('le coût du projet reste caché aux simples membres', r.status === 200 && r.json.cost === undefined && r.json.time.hours === 5, r.json);
  await mgr('POST', `${P}/${proj}/costs`, { label: 'Rayons', amount: 80000 });
  r = await mgr('GET', `${P}/${proj}/summary`);
  check('dépassement du budget signalé', r.json.cost.overBudget === true, r.json.cost);
  r = await mgr('GET', `${P}/workload`);
  check('charge par personne (tâches ouvertes, heures estimées et saisies)', r.json.items.some((x) => x.name === 'Paul' && x.openTasks === 1 && x.estimatedHours === 6 && x.loggedHours30d === 5), r.json);
  r = await mem('GET', `${P}/workload`);
  check('charge par personne réservée aux responsables', r.status === 403);
  r = await mgr('POST', `${P}/${proj}/milestones`, { title: 'Inauguration', due: addDays(-2) });
  const ms = r.json.id;
  r = await mgr('GET', `${P}/${proj}/summary`);
  check('jalon en retard repéré', r.json.milestones[0].late === true);
  await mgr('PUT', `${P}/milestones/${ms}`, { done: true });
  r = await mgr('GET', `${P}/${proj}/summary`);
  check('jalon terminé', r.json.milestones[0].done === true && r.json.milestones[0].late === false);
  r = await mem('POST', `${P}/tasks/${tB}/comments`, { content: 'Rayons livrés' });
  check('commentaire ajouté', r.status === 201);
  r = await mgr('GET', `${P}/tasks/${tB}/comments`);
  check('commentaires listés avec l\'auteur', r.json.items[0].who === 'Paul');
  r = await mem('POST', `${P}/${proj}/files?name=plan`, PNG);
  check('pièce jointe chiffrée au projet', r.status === 201, r.json);
  const pf = r.json.id;
  const row = await dbx.prepare('SELECT data FROM legal_files WHERE id = ?').get(pf);
  check('pièce de projet chiffrée dans la base', !Buffer.from(row.data).includes(Buffer.from('PIECE-PROJET')));
  r = await mgr('GET', `${P}/files/${pf}/file`);
  check('pièce de projet relue', r.status === 200 && Buffer.compare(r.buf, PNG) === 0);
  r = await other('GET', `${ws(org)}/projects/${proj}/files`);
  check('autre organisation : aucun accès aux pièces', r.status === 404);
  // récurrence
  r = await mgr('POST', `${P}/tasks`, { projectId: proj, title: 'Inventaire hebdomadaire', assigneeId: memId });
  const tR = r.json.id;
  r = await mgr('PUT', `${P}/tasks/${tR}/plan`, { recurrence: 'weekly', recurNext: addDays(0) });
  check('récurrence hebdomadaire programmée', r.status === 200);
  r = await mgr('POST', `${P}/recurring/run`, {});
  check('une occurrence créée', r.json.created === 1, r.json);
  r = await mgr('POST', `${P}/recurring/run`, {});
  check('pas de doublon au second passage', r.json.created === 0, r.json);
  r = await mgr('GET', `${P}/tasks?project=${proj}`);
  check('la nouvelle occurrence existe, à faire', r.json.tasks.filter((t) => t.title === 'Inventaire hebdomadaire').length === 2);
  r = await mgr('PUT', `${P}/tasks/${tR}/plan`, { recurrence: 'yearly' });
  check('récurrence inconnue refusée', r.status === 400);

  // ---------- Juridique ----------
  const L = `${O}/legal`;
  r = await mem('GET', `${L}/registers`);
  check('registres : fermés aux membres', r.status === 403);
  r = await mgr('POST', `${L}/registers`, { kind: 'associe', title: 'Associé', holder: 'A', shares: 60 });
  check('registres : écriture réservée aux administrateurs', r.status === 403);
  await owner('POST', `${L}/registers`, { kind: 'associe', title: 'Associé', holder: 'Awa', shares: 60 });
  await owner('POST', `${L}/registers`, { kind: 'associe', title: 'Associé', holder: 'Marc', shares: 40 });
  await owner('POST', `${L}/registers`, { kind: 'ag', title: 'AG ordinaire', date: addDays(-30), ref: 'PV-01' });
  await owner('POST', `${L}/registers`, { kind: 'rccm', title: 'RCCM', ref: 'RC/DLA/2024/B/001' });
  r = await owner('POST', `${L}/registers`, { kind: 'inconnu', title: 'X' });
  check('type de registre inconnu refusé', r.status === 400);
  r = await mgr('GET', `${L}/registers-summary`);
  check('répartition du capital et dernière AG', r.json.totalShares === 100 && r.json.partners[0].percent === 60 && r.json.lastAg.title === 'AG ordinaire', r.json);
  r = await owner('POST', `${L}/compliance/seed`, {});
  check('calendrier de conformité Cameroun pré-rempli', r.status === 200 && r.json.added >= 5, r.json);
  r = await owner('POST', `${L}/compliance/seed`, {});
  check('pas de doublon au second remplissage', r.json.added === 0);
  r = await mgr('GET', `${L}/compliance`);
  check('toutes les lignes sont des exemples « à vérifier »', r.json.items.length >= 5 && r.json.items.every((c) => c.source === 'exemple' && c.verify === true), r.json.items[0]);
  const monthly = r.json.items.find((c) => c.recurrence === 'monthly');
  r = await owner('POST', `${L}/compliance/${monthly.id}/done`, {});
  r = await mgr('GET', `${L}/compliance`);
  const after = r.json.items.find((c) => c.id === monthly.id);
  check('échéance mensuelle faite : la suivante est reprogrammée', after.status === 'todo' && after.dueDate > monthly.dueDate, { before: monthly.dueDate, after: after.dueDate });
  r = await owner('POST', `${L}/compliance`, { title: 'Dépôt à faire', dueDate: addDays(-1), verify: true });
  check('obligation ajoutée à la main', r.status === 201);
  r = await mgr('GET', `${O}/dashboard/alerts`);
  check('alertes : obligation de conformité échue', r.json.alerts.some((a) => a.module === 'legal' && /Dépôt à faire/.test(a.title)), r.json.alerts.filter((a) => a.module === 'legal'));

  // ---------- Procédures ----------
  const S = `${O}/structure`;
  r = await owner('POST', `${S}/processes`, { title: 'Ouverture de caisse', category: 'Caisse', steps: ['Compter le fond de caisse', 'Ouvrir le logiciel'], ownerId: mgrId, reviewMonths: 6 });
  const pr = r.json.id;
  r = await mem('GET', `${S}/processes`);
  let p0 = r.json.processes.find((p) => p.id === pr);
  check('procédure : version 1, propriétaire, révision programmée', p0.version === 1 && p0.owner === 'Marc' && p0.nextReview && p0.readByMe === false, p0);
  r = await owner('PUT', `${S}/processes/${pr}`, { steps: ['Compter le fond de caisse', 'Ouvrir le logiciel', 'Signer le registre'] });
  check('modification : nouvelle version', r.json.version === 2, r.json);
  r = await mem('GET', `${S}/processes/${pr}/versions`);
  check('historique : l\'ancienne version est conservée', r.json.current.version === 2 && r.json.versions[0].version === 1 && r.json.versions[0].steps.length === 2, r.json);
  r = await mem('GET', `${O}/notices`);
  check('l\'équipe est prévenue de relire', r.json.items.some((n) => /à relire/.test(n.text)));
  r = await mem('POST', `${S}/processes/${pr}/read`, {});
  check('accusé de lecture enregistré', r.status === 200 && r.json.version === 2);
  r = await mgr('GET', `${S}/processes/${pr}/reads`);
  check('qui a lu la version en cours', r.json.items.find((i) => i.name === 'Paul').readAt && !r.json.items.find((i) => i.name === 'Awa').readAt, r.json);
  await dbx.prepare('UPDATE processes SET next_review = ? WHERE id = ?').run(addDays(-3), pr);
  r = await mgr('GET', `${S}/processes-due`);
  check('révision en retard listée', r.json.items.some((i) => i.id === pr));
  r = await mgr('GET', `${O}/dashboard/alerts`);
  check('alerte de révision de procédure', r.json.alerts.some((a) => a.module === 'processes' && /révis/.test(a.text)));
  r = await mem('POST', `${S}/processes/${pr}/reviewed`, {});
  check('révision validée par le propriétaire ou un administrateur seulement', r.status === 403);
  r = await mgr('POST', `${S}/processes/${pr}/reviewed`, {});
  check('le propriétaire de la procédure valide la révision', r.status === 200 && r.json.nextReview > addDays(100));

  // ---------- Équipe : audit et propriété ----------
  r = await owner('PUT', `${O}/members/${memId}`, { title: 'Vendeur senior' });
  r = await owner('GET', `${O}/audit?entity=member`);
  check('audit des changements d\'équipe (avant / après)', r.json.items.some((i) => i.action === 'update' && i.before.title !== i.after.title && i.who === 'Awa'), r.json.items[0]);
  r = await owner('GET', `${O}/audit?entity=decision`);
  check('audit des décisions filtrable', r.json.items.length >= 3 && r.json.items.every((i) => i.entity === 'decision'));
  r = await owner('GET', `${O}/audit?userId=${mgrId}&limit=5`);
  check('audit filtrable par personne', r.json.items.every((i) => i.userId === mgrId));
  r = await mgr('POST', `${O}/ownership-transfer`, { userId: mgrId, confirm: 'Boutique Awa' });
  check('transfert : réservé au propriétaire', r.status === 403);
  r = await owner('POST', `${O}/ownership-transfer`, { userId: mgrId, confirm: 'faux' });
  check('transfert : confirmation exigée', r.status === 400);
  r = await owner('POST', `${O}/ownership-transfer`, { userId: mgrId, confirm: 'Boutique Awa' });
  check('propriété transférée', r.status === 200, r.json);
  r = await mgr('GET', `${O}`);
  check('le nouveau propriétaire a le rôle owner', r.json.me.role === 'owner');
  r = await owner('GET', `${O}`);
  check('l\'ancien propriétaire devient administrateur', r.json.me.role === 'admin');
  r = await mgr('GET', `${O}/audit?entity=ownership`);
  check('transfert journalisé', r.json.items.length === 1);
});
